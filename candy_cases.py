"""糖果题 v2：独立题面、金标和人工证明审核要求。"""

PROMPT_A = """在一个黑色袋子里有苹果、桃子、西瓜三种口味，每种口味有圆形和五角星形。形状可以靠手感分辨，并且你可以主动选择要取圆形还是五角星形。数量为：圆形苹果7、圆形桃子9、圆形西瓜8；五角星苹果7、五角星桃子6、五角星西瓜4。你要保证手中有圆形苹果+五角星桃子，或五角星苹果+圆形桃子。最少需要取多少颗？请说明可控动作、给出充分性证明和20颗不够的下界证明。"""

PROMPT_B = """在一个黑色袋子里有苹果、桃子、西瓜三种口味，每种口味有圆形和五角星形。你只能盲抽，必须在开始前决定总数，不能主动选择形状。数量为：圆形苹果7、圆形桃子9、圆形西瓜8；五角星苹果7、五角星桃子6、五角星西瓜4。你要保证手中有圆形苹果+五角星桃子，或五角星苹果+圆形桃子。最少需要取多少颗？请给出一个28颗仍然失败的构造，并说明为什么再取一颗就能保证。"""

CASES = {
    "A": {
        "prompt": PROMPT_A,
        "expected_answer": 21,
        "proof_requirements": [
            "明确可以主动选择形状，并给出取糖策略",
            "证明策略最多21颗即可保证成功",
            "证明任何策略20颗仍不能保证成功",
        ],
    },
    "B": {
        "prompt": PROMPT_B,
        "expected_answer": 29,
        "proof_requirements": [
            "只能盲抽且必须事先决定总数",
            "给出28颗仍失败的具体构造",
            "证明失败集合至多28颗，因此29颗保证成功",
        ],
    },
}


def case_prompt(case: str) -> str:
    return (
        "不使用任何外部工具回答以下问题：\n\n"
        + CASES[case]["prompt"]
        + "\n\n请完整说明推理，最后单独一行写“最终答案：N”，N为最少颗数。"
    )
